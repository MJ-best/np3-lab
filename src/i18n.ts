const DICTS: Record<Lang, Dict> = { ko, en, ja };

function initialLang(): Lang {
  const stored = readStore<string>("lang");
  if (stored === "ko" || stored === "en" || stored === "ja") return stored;
  const nav = typeof navigator !== "undefined" ? navigator.language?.toLowerCase() ?? "" : "";
  return nav.startsWith("ko") ? "ko" : nav.startsWith("ja") ? "ja" : "en";
}

export const lang = signal<Lang>(initialLang());

export function setLang(next: Lang) {
  lang.value = next;
  writeStore("lang", next);
  document.documentElement.lang = next;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang.value][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function tx(text: LocalizedText | undefined): string {
  if (!text) return "";
  if (typeof text === "string") return text;
  return pickText(text, lang.value);
}

/** Japanese falls back to English (most recipe notes exist in Korean and English only). */
const FALLBACK: Record<Lang, Lang[]> = { ko: ["ko", "en", "ja"], en: ["en", "ko", "ja"], ja: ["ja", "en", "ko"] };

export function pickText(text: { ko?: string; en?: string; ja?: string }, l: Lang): string {
  for (const k of FALLBACK[l]) if (text[k]) return text[k]!;
  return "";
}

