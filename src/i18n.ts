export type MessageKey = keyof typeof ko;
const DICTS: Record<Lang, Dict> = { ko, en };

function initialLang(): Lang {
  const stored = readStore<string>("lang");
  if (stored === "ko" || stored === "en") return stored;
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export const lang = signal<Lang>(initialLang());

export function setLang(next: Lang) {
  lang.value = next;
  writeStore("lang", next);
  document.documentElement.lang = next;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang.value][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function tx(text: LocalizedText | undefined): string {
  if (!text) return "";
  if (typeof text === "string") return text;
  return text[lang.value] ?? text.ko ?? text.en ?? "";
}

